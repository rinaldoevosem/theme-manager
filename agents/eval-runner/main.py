"""Eval Runner — Overnight self-improvement loop for theme agents.

Usage:
    python main.py --overnight              # Full loop
    python main.py --create-tasks           # Just create Paperclip tasks
    python main.py --score <run_dir>        # Re-score a previous run
    python main.py --report <run_dir>       # Regenerate report
    python main.py --list-runs              # List previous runs
    python main.py --cleanup-eval-tasks     # Delete EVAL: tasks from Paperclip
"""

