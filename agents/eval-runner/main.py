# CLI
# ----------------------------------------------------------------------------


def main() -> None:
    parser = argparse.ArgumentParser(description="Theme agent eval runner")
    parser.add_argument("--overnight", action="store_true", help="Run full eval loop")
    parser.add_argument("--create-tasks", action="store_true", help="Just create Paperclip tasks")
    parser.add_argument("--score", metavar="RUN_DIR", help="Re-score a previous run")
    parser.add_argument("--report", metavar="RUN_DIR", help="Regenerate report from scores")
    parser.add_argument("--list-runs", action="store_true", help="List previous runs")
    parser.add_argument(
        "--cleanup-eval-tasks",
        action="store_true",
        help="Delete all [EVAL:...] tasks from Paperclip",
    )
    parser.add_argument("--suite", help="Filter cases by suite name")
    parser.add_argument("--max-cases", type=int, help="Limit number of cases")
    parser.add_argument(
        "--skip-run",
        action="store_true",
        help="With --overnight: only create tasks, don't run heartbeat",
    )
    args = parser.parse_args()

    if args.overnight:
        asyncio.run(overnight(args.suite, args.max_cases, args.skip_run))
    elif args.create_tasks:
        asyncio.run(overnight(args.suite, args.max_cases, skip_run=True))
    elif args.score:
        asyncio.run(rescore_run(Path(args.score)))
    elif args.report:
        asyncio.run(regenerate_report(Path(args.report)))
    elif args.list_runs:
        list_runs()
    elif args.cleanup_eval_tasks:
        async def _cleanup():
            client = PaperclipClient(config.paperclip_url, config.company_id)
            try:
                stats = await cleanup_eval_tasks(client)
                print(
                    f"[cleanup] Deleted {stats['deleted']} active eval tasks "
                    f"(kept {stats['kept_done']} done as historical records, "
                    f"{stats['failed']} failed)"
                )
            finally:
                await client.close()
        asyncio.run(_cleanup())
    else:
        parser.print_help()
        sys.exit(1)


if __name__ == "__main__":
    main()
