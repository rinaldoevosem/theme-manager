# ----------------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------------


def make_run_id() -> str:
    return datetime.now().strftime("%Y-%m-%dT%H-%M")


def save_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2, default=str))


def load_json(path: Path) -> Any:
    return json.loads(path.read_text())


def _validate_cases(cases: list[dict]) -> list[dict]:
    valid = []
    for c in cases:
        errors = validate_case(c)
        if errors:
            print(f"[warn] Skipping invalid case '{c.get('id', '?')}': {errors}", file=sys.stderr)
            continue
        valid.append(c)
    return valid


# ----------------------------------------------------------------------------
# Phase 1: Create tasks
# ----------------------------------------------------------------------------


async def create_eval_tasks(
    client: PaperclipClient,
    cases: list[dict],
    run_id: str,
) -> list[dict]:
    """Create Paperclip issues for each eval case. Returns case_id ↔ issue_id map."""
    task_map = []

    for case in cases:
        title = f"[EVAL:{run_id}] {case['title']}"
        description = (
            f"**Eval Case:** `{case['id']}`\n\n"
            f"{case['description']}\n\n"
            f"---\n"
            f"_Theme directory: `{config.theme_dir}`_\n"
            f"_Generated by eval-runner. This is a synthetic test task._"
        )

        issue = await client.create_issue(
            title=title,
            description=description,
            assignee_agent_id=config.architect_agent_id,
            metadata={
                "eval_run_id": run_id,
                "eval_case_id": case["id"],
                "eval_suite": case.get("suite", "unknown"),
            },
        )

        task_map.append({
            "case_id": case["id"],
            "issue_id": issue["id"],
            "issue_identifier": issue.get("identifier", ""),
            "title": case["title"],
            "suite": case.get("suite", "unknown"),
        })
        print(f"[create] {case['id']} -> {issue.get('identifier', issue['id'])}")

    return task_map


# ----------------------------------------------------------------------------
# Phase 2: Trigger architect heartbeat and wait
# ----------------------------------------------------------------------------


def trigger_architect_heartbeat(timeout_seconds: int) -> tuple[int, str, str]:
    """Run the theme-architect heartbeat as a subprocess. Returns (exit_code, stdout, stderr)."""
    venv_python = config.architect_dir / ".venv" / "bin" / "python3.14"
    if not venv_python.exists():
        venv_python = config.architect_dir / ".venv" / "bin" / "python"
    if not venv_python.exists():
        venv_python = Path("python3")

    print(f"[run] Triggering architect heartbeat: {venv_python} main.py --heartbeat")
    print(f"[run] cwd={config.architect_dir} timeout={timeout_seconds}s")

    try:
        proc = subprocess.run(
            [str(venv_python), "main.py", "--heartbeat"],
            cwd=str(config.architect_dir),
            capture_output=True,
            text=True,
            timeout=timeout_seconds,
        )
        return proc.returncode, proc.stdout, proc.stderr
    except subprocess.TimeoutExpired as e:
        return -1, e.stdout or "", f"TIMEOUT after {timeout_seconds}s"


_DONE_RE = re.compile(
    r"\[Done\]\s*Cost:\s*\$([\d.]+)\s*\|\s*Turns:\s*(\d+)\s*\|\s*Duration:\s*([\d.]+)s"
)
_PROCESSING_RE = re.compile(r"\[heartbeat\]\s*Processing:\s*(.+)$", re.MULTILINE)


def parse_heartbeat_stdout(stdout: str) -> list[dict]:
    """Parse architect heartbeat stdout into per-task cost/duration records.

    The architect prints `[heartbeat] Processing: <title>` then `[Done] Cost:...`
    for each task in order. We pair them up.
    """
    lines = stdout.splitlines()
    tasks: list[dict] = []
    current_title: str | None = None

    for line in lines:
        proc_match = _PROCESSING_RE.search(line)
        if proc_match:
            current_title = proc_match.group(1).strip()
            continue

        done_match = _DONE_RE.search(line)
        if done_match and current_title:
            tasks.append({
                "title": current_title,
                "cost_usd": float(done_match.group(1)),
                "turns": int(done_match.group(2)),
                "duration_ms": int(float(done_match.group(3)) * 1000),
            })
            current_title = None

    return tasks


async def collect_results(
    client: PaperclipClient,
    task_map: list[dict],
    heartbeat_stdout: str = "",
) -> dict[str, dict]:
    """Fetch issues + comments for each eval task, return case_id -> result dict."""
    results: dict[str, dict] = {}

    issues = await client.list_issues(assignee_agent_id=config.architect_agent_id)
    issues_by_id = {i["id"]: i for i in issues}

    # Parse cost/duration from heartbeat stdout
    stdout_tasks = parse_heartbeat_stdout(heartbeat_stdout)
    # Build title -> {cost, duration} map (titles include the [EVAL:run_id] prefix)
    metrics_by_title: dict[str, dict] = {}
    for st in stdout_tasks:
        metrics_by_title[st["title"]] = st

    for entry in task_map:
        issue_id = entry["issue_id"]
        case_id = entry["case_id"]
        issue = issues_by_id.get(issue_id)

        if not issue:
            results[case_id] = {
                "issue_id": issue_id,
                "status": "missing",
                "output": "",
                "cost_usd": 0.0,
                "duration_ms": 0,
            }
            continue

        comments = await client.get_comments(issue_id)
        agent_comments = [c for c in comments if c.get("body") or c.get("content")]
        output = "\n\n".join(c.get("body") or c.get("content") or "" for c in agent_comments)

        # Match cost/duration via the issue's full title (includes [EVAL:...] prefix)
        full_title = issue.get("title", "")
        metrics = metrics_by_title.get(full_title, {})

        results[case_id] = {
            "issue_id": issue_id,
            "status": issue.get("status", "unknown"),
            "output": output,
            "cost_usd": metrics.get("cost_usd", 0.0),
            "duration_ms": metrics.get("duration_ms", 0),
            "turns": metrics.get("turns", 0),
        }

    return results


# ----------------------------------------------------------------------------
# Cleanup
# ----------------------------------------------------------------------------


async def cleanup_eval_tasks(client: PaperclipClient) -> dict:
    """Delete non-done [EVAL:...] tasks. Done tasks are kept as historical records."""
    issues = await client.list_issues()
    deleted = 0
    kept_done = 0
    failed = 0

    for issue in issues:
        title = issue.get("title", "")
        if not title.startswith("[EVAL:"):
            continue

        status = issue.get("status", "")
        if status == "done":
            kept_done += 1
            continue

        ok = await client.delete_issue(issue["id"])
        if ok:
            deleted += 1
            print(f"[delete] {issue.get('identifier', issue['id'])}: {title}")
        else:
            failed += 1

    return {"deleted": deleted, "kept_done": kept_done, "failed": failed}


# ----------------------------------------------------------------------------
# Phase 3: Overnight loop
# ----------------------------------------------------------------------------


async def overnight(
    suite_filter: str | None = None,
    max_cases: int | None = None,
    skip_run: bool = False,
) -> None:
    """Full loop: load → create → run → score → report."""
    run_id = make_run_id()
    run_dir = config.results_dir / f"run_{run_id}"
    run_dir.mkdir(parents=True, exist_ok=True)

    print(f"[overnight] Starting eval run {run_id}")
    print(f"[overnight] Results dir: {run_dir}")

    # Validate config
    if not config.architect_agent_id or not config.company_id:
        print("[error] Missing ARCHITECT_AGENT_ID or PAPERCLIP_COMPANY_ID in .env", file=sys.stderr)
        sys.exit(1)
    if not config.architect_dir.is_dir():
        print(f"[error] Architect dir not found: {config.architect_dir}", file=sys.stderr)
        sys.exit(1)

    # Load cases
    cases = load_eval_cases(config.eval_cases_dir, suite_filter=suite_filter)
    cases = _validate_cases(cases)
    if max_cases:
        cases = cases[:max_cases]
    if not cases:
        print("[error] No eval cases loaded", file=sys.stderr)
        sys.exit(1)
    print(f"[overnight] Loaded {len(cases)} cases")

    save_json(run_dir / "cases.json", cases)

    client = PaperclipClient(config.paperclip_url, config.company_id)

    try:
        # Phase 1: Create tasks
        print(f"[overnight] Creating {len(cases)} Paperclip tasks...")
        task_map = await create_eval_tasks(client, cases, run_id)
        save_json(run_dir / "task_map.json", task_map)

        if skip_run:
            print("[overnight] --skip-run set, exiting after task creation")
            return

        # Phase 2: Trigger heartbeat and wait
        timeout_s = max(len(cases) * config.timeout_per_case_min * 60, 600)
        exit_code, stdout, stderr = trigger_architect_heartbeat(timeout_s)
        (run_dir / "heartbeat_stdout.log").write_text(stdout)
        (run_dir / "heartbeat_stderr.log").write_text(stderr)
        print(f"[overnight] Heartbeat exit code: {exit_code}")

        # Phase 3: Collect results
        print("[overnight] Collecting results from Paperclip...")
        results = await collect_results(client, task_map, heartbeat_stdout=stdout)
        save_json(run_dir / "raw_results.json", results)

        # Phase 4: Score
        print("[overnight] Scoring...")
        scores = score_all(cases, results)
        save_json(run_dir / "scores.json", scores)

        # Phase 5: Feedback
        feedback = analyze(scores, cases)
        save_json(run_dir / "feedback.json", feedback)

        # Phase 6: Report
        previous = load_previous_scores(config.results_dir, run_id)
        report = generate_report(run_id, cases, scores, feedback, previous)
        report_path = run_dir / "report.md"
        report_path.write_text(report)

        print_terminal_summary(scores, feedback, report_path)
    finally:
        await client.close()


# ----------------------------------------------------------------------------
# Other commands
# ----------------------------------------------------------------------------


async def rescore_run(run_dir: Path) -> None:
    cases = load_json(run_dir / "cases.json")
    results = load_json(run_dir / "raw_results.json")
    scores = score_all(cases, results)
    save_json(run_dir / "scores.json", scores)
    feedback = analyze(scores, cases)
    save_json(run_dir / "feedback.json", feedback)
    print(f"[rescore] Updated {run_dir}/scores.json and feedback.json")


async def regenerate_report(run_dir: Path) -> None:
    cases = load_json(run_dir / "cases.json")
    scores = load_json(run_dir / "scores.json")
    feedback = load_json(run_dir / "feedback.json")
    run_id = run_dir.name.replace("run_", "")
    previous = load_previous_scores(config.results_dir, run_id)
    report = generate_report(run_id, cases, scores, feedback, previous)
    report_path = run_dir / "report.md"
    report_path.write_text(report)
    print(f"[report] Wrote {report_path}")


def list_runs() -> None:
    if not config.results_dir.exists():
        print("(no runs yet)")
        return
    runs = sorted(p for p in config.results_dir.glob("run_*") if p.is_dir())
    if not runs:
        print("(no runs yet)")
        return

    print(f"{'Run ID':<22} {'Cases':>6} {'Pass':>6} {'Score':>7} {'Cost':>8}")
    print("-" * 55)
    for run in runs:
        scores_file = run / "scores.json"
        if not scores_file.exists():
            print(f"{run.name:<22} (incomplete)")
            continue
        scores = json.loads(scores_file.read_text())
        n = max(len(scores), 1)
        avg = sum(s["composite"] for s in scores) / n
        passed = sum(1 for s in scores if s["accuracy"] >= 0.6)
        cost = sum(s.get("cost_usd", 0) for s in scores)
        print(f"{run.name:<22} {len(scores):>6} {passed/n:>5.0%} {avg:>7.3f} ${cost:>7.2f}")


